#Boolean Expression Practice

print(f"{not True and False}\t# not True is False; False and False is False")
print(f"{True or False and False}\t# False and False is False; True or False is True")
print(f"{not (5 > 3)}\t# 5 > 3 is True; not True is False")
print(f"{10 == 10 and 4 != 4}\t# 10 == 10 is True; 4 != 4 is False; True and False is False")
print(f"{not False or not True}\t# not False is True; not True is False; True or False is True")
